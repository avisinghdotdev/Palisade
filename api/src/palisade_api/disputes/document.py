"""The record PDF filed with the evidence: the facts record, printed for PayPal's reviewer."""

from datetime import datetime
from pathlib import Path

from fpdf import FPDF
from fpdf.enums import XPos, YPos

from palisade_api.disputes.facts import NOT_SPECIFIED, SIGNERS, Facts
from palisade_api.shop.catalog import Money

# DejaVu Sans, so any name or product the record holds prints; its licence sits beside it.
FONTS = Path(__file__).parent / "fonts"
FONT = "DejaVu"
DOCUMENT_NAME = "palisade-record.pdf"
PAGE_WIDTH = 180
LABEL_WIDTH = 55
BODY_SIZE = 9.5

KINDS = {
    "cart": "Cart mandate: one exact cart, signed at checkout",
    "intent": "Intent mandate: a cap and categories, signed up front",
}


def when(moment: datetime | None) -> str:
    return NOT_SPECIFIED if moment is None else moment.strftime("%Y-%m-%d %H:%M:%S UTC")


def amount(money: Money) -> str:
    return f"{money.value} {money.currency_code}"


def render(facts: Facts) -> bytes:
    """The facts record as a PDF; every section prints what the store holds, or "Not specified"."""
    pdf = FPDF(format="A4")
    pdf.set_title(f"Palisade record for PayPal dispute {facts.dispute.id}")
    pdf.set_author("Palisade")
    pdf.set_creator("Palisade")
    pdf.add_font(FONT, fname=FONTS / "DejaVuSans.ttf")
    pdf.add_font(FONT, style="B", fname=FONTS / "DejaVuSans-Bold.ttf")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    _title(pdf, facts)
    _section(pdf, "Dispute", _dispute(facts))
    _section(pdf, "Order", _order(facts))
    _lines(
        pdf,
        "Order lines",
        [
            (line.name, f"US {line.size} × {line.quantity}", amount(line.line_total))
            for line in facts.order.lines
        ],
    )
    _section(pdf, "Shipment", _shipment(facts))
    _section(pdf, "Buyer's signed mandate", _mandate(facts))
    if facts.mandate is not None and facts.mandate.lines:
        _lines(
            pdf,
            "Items the buyer signed for",
            [
                (
                    line.name,
                    f"US {line.size} × {line.quantity}",
                    amount(line.unit_price),
                )
                for line in facts.mandate.lines
            ],
        )
    _section(pdf, "Shopping agent", _agent(facts))
    _section(pdf, "Merchant policy the purchase passed", _policy(facts))
    _section(
        pdf,
        "PayPal calls",
        [
            (
                f"{call.action} at {when(call.at)}",
                f"HTTP {call.status_code if call.status_code is not None else NOT_SPECIFIED}, debug id {call.debug_id or NOT_SPECIFIED}",
            )
            for call in facts.paypal_calls
        ]
        or [("Calls", "none")],
    )
    _footer(pdf, facts)
    return bytes(pdf.output())


def _title(pdf: FPDF, facts: Facts) -> None:
    pdf.set_font(FONT, style="B", size=16)
    pdf.cell(PAGE_WIDTH, 10, "Palisade Record", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font(FONT, size=BODY_SIZE)
    pdf.multi_cell(
        PAGE_WIDTH,
        5,
        f"PayPal dispute {facts.dispute.id} on order {facts.order.number} at {facts.merchant}."
        + f" Generated by Palisade {when(facts.generated_at)} from the store's own records."
        + " Palisade records how a shopping agent bought from the store under a mandate the"
        + " buyer signed, and verifies every request the agent made.",
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(3)


def _section(pdf: FPDF, heading: str, rows: list[tuple[str, str]]) -> None:
    pdf.set_font(FONT, style="B", size=11)
    pdf.cell(PAGE_WIDTH, 8, heading, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font(FONT, size=BODY_SIZE)
    with pdf.table(
        col_widths=(LABEL_WIDTH, PAGE_WIDTH - LABEL_WIDTH),
        first_row_as_headings=False,
        borders_layout="HORIZONTAL_LINES",
        line_height=5,
        padding=1,
        text_align=("LEFT", "LEFT"),
    ) as table:
        for label, value in rows:
            row = table.row()
            row.cell(label)
            row.cell(value)
    pdf.ln(4)


def _lines(pdf: FPDF, heading: str, rows: list[tuple[str, str, str]]) -> None:
    pdf.set_font(FONT, style="B", size=11)
    pdf.cell(PAGE_WIDTH, 8, heading, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font(FONT, size=BODY_SIZE)
    with pdf.table(
        col_widths=(100, 40, 40),
        borders_layout="HORIZONTAL_LINES",
        line_height=5,
        padding=1,
        text_align=("LEFT", "LEFT", "RIGHT"),
    ) as table:
        header = table.row()
        for name in ("Item", "Size and quantity", "Price"):
            header.cell(name)
        for item, size, price in rows:
            row = table.row()
            row.cell(item)
            row.cell(size)
            row.cell(price)
    pdf.ln(4)


def _footer(pdf: FPDF, facts: Facts) -> None:
    pdf.set_font(FONT, size=8)
    signer = None if facts.mandate is None else facts.mandate.signed_by
    note = (
        " The mandate was signed by the demo signer, a simulated buyer, as this store runs in"
        + " PayPal's sandbox."
        if signer == SIGNERS["demo_signer"]
        else ""
    )
    pdf.multi_cell(
        PAGE_WIDTH,
        4,
        "Hashes are SHA-256, hex. Times are UTC. The custom id PayPal holds on the payment is"
        + f" the mandate's id and token hash joined with a colon.{note}",
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )


def _dispute(facts: Facts) -> list[tuple[str, str]]:
    dispute = facts.dispute
    return [
        ("Dispute id", dispute.id),
        ("Reason", dispute.reason),
        ("Stage and status", f"{dispute.stage}, {dispute.status}"),
        ("Channel", dispute.channel or NOT_SPECIFIED),
        ("Amount", amount(dispute.amount)),
        ("Opened", when(dispute.opened_at)),
        (
            "Buyer's messages",
            "\n".join(dispute.buyer_messages) if dispute.buyer_messages else "none",
        ),
    ]


def _order(facts: Facts) -> list[tuple[str, str]]:
    order = facts.order
    return [
        ("Order number", order.number),
        ("Placed", when(order.placed_at)),
        (
            "Placed by",
            "A shopping agent, under the buyer's signed mandate"
            if order.channel == "agent"
            else "The buyer, in the store",
        ),
        ("Status", order.status),
        ("Total", amount(order.total)),
        ("PayPal order id", order.paypal_order_id or NOT_SPECIFIED),
        ("Capture id (seller transaction id)", order.capture_id or NOT_SPECIFIED),
        ("Custom id on the payment", order.custom_id or NOT_SPECIFIED),
    ]


def _shipment(facts: Facts) -> list[tuple[str, str]]:
    shipment = facts.shipment
    if shipment is None:
        return [("Shipment", "Not marked shipped")]
    return [
        ("Carrier", shipment.carrier),
        ("Tracking number", shipment.tracking_number),
        ("PayPal tracker", shipment.paypal_tracker_id),
        ("Shipped", when(shipment.shipped_at)),
    ]


def _mandate(facts: Facts) -> list[tuple[str, str]]:
    mandate = facts.mandate
    if mandate is None:
        return [("Mandate", "None: the buyer placed the order in person")]
    named = {
        True: "Yes: PayPal's custom value on the payment is this mandate's id and hash",
        False: "No: PayPal's custom value on the payment differs",
        None: NOT_SPECIFIED,
    }[mandate.named_on_payment]
    return [
        ("Mandate id", str(mandate.id)),
        ("Kind", KINDS.get(mandate.kind, mandate.kind)),
        ("Signed by", mandate.signed_by or NOT_SPECIFIED),
        ("Signed", when(mandate.signed_at)),
        ("Spending cap", amount(mandate.cap)),
        ("Categories", ", ".join(mandate.categories) or "any"),
        ("Valid until", when(mandate.expires_at)),
        ("Token hash", mandate.token_hash),
        ("Policy hash the buyer signed under", mandate.policy_hash),
        ("Named on the disputed payment", named),
    ]


def _agent(facts: Facts) -> list[tuple[str, str]]:
    agent = facts.agent
    if agent is None:
        return [("Agent", "None: the buyer placed the order in person")]
    return [
        ("Agent id", agent.id),
        ("Name", agent.name),
        ("Registered public key (Ed25519, base64)", agent.public_key),
        (
            "Signed requests verified",
            f"{agent.verified_requests} (RFC 9421 HTTP message signatures)",
        ),
    ]


def _policy(facts: Facts) -> list[tuple[str, str]]:
    policy = facts.policy
    if policy is None:
        return [("Policy", NOT_SPECIFIED)]
    return [
        ("Policy hash", policy.hash),
        ("Allowed agents", ", ".join(policy.allowed_agents)),
        ("Per-order cap", amount(policy.per_order_cap)),
        ("Per-agent daily cap", amount(policy.per_agent_daily_cap)),
        ("Blocked categories", ", ".join(policy.blocked_categories) or "none"),
    ]
